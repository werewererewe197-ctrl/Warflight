const cache = {};
export function iconPath(name) {
  if (!cache[name]) cache[name] = new Path2D(ICONS[name] || ICONS.help);
  return cache[name];
}

// Рисует значок на канвасе; (x, y) — центр, size — размер в пикселях.
export function drawIcon(ctx, name, x, y, size, color = '#fff', lw = 2) {
  ctx.save();
  ctx.translate(x - size / 2, y - size / 2);
  const s = size / 24;
  ctx.scale(s, s);
  ctx.strokeStyle = color;
  ctx.lineWidth = lw / s;   // толщина линии в экранных пикселях
  ctx.lineCap = 'round'; ctx.lineJoin = 'round';
  ctx.stroke(iconPath(name));
  ctx.restore();
}

// SVG-разметка значка для DOM.
export function svg(name, cls = '') {
  return `<svg class="ic ${cls}" viewBox="0 0 24 24" aria-hidden="true"><path d="${ICONS[name] || ICONS.help}"/></svg>`;
}
